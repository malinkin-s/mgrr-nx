#!/usr/bin/env python3
"""Convert our XenonRecomp analysis (x360_work/mgrr.toml functions, switch_tables.toml) into ReXGlue codegen includes.

  to_rexglue.py            -> game/analysis_functions.toml, game/analysis_switch_tables.toml

ReXGlue schema (sdk/src/codegen/config.cpp): [functions] "0xADDR" = { size = N } and
[[switch_tables]] address = <bctr address>, register = <index register>, labels = [...].
Our [[switch]] entries: base = <bctr address>, r = <register>, labels = [...] (find_jumptables.py).
"""
import re, sys, tomllib

ROOT = '/home/lucidfear/Projects/mgr-nx/'
# Entries of our list that are not functions for ReXGlue (each one checked by hand).
EXCLUDE = {
    0x82ADBC0C: 'label inside sub_82ADBA90 (only reached by its own bgt at 0x82ADBC.. range); the end of 0x82ADBA90 is in overrides.toml',
}


def main():
    cfg = tomllib.load(open(ROOT + 'x360_work/mgrr.toml', 'rb'))
    funcs = cfg['main'].get('functions', [])
    out = ['# Generated by tools/to_rexglue.py from x360_work/mgrr.toml (our XenonRecomp analysis). Do not edit by hand.',
           '# Starts of functions that the .pdata table does not describe or describes wrongly (switch bodies, nested entries).', '',
           '[functions]']
    for f in sorted(funcs, key=lambda f: f['address']):
        if f['address'] in EXCLUDE: continue
        out.append('"0x%08X" = { }' % f['address'])        # start only: several of our sizes nest (XenonRecomp tolerated it, ReXGlue does not); the analyzer finds the end
    extra = [l.split()[0] for l in open(ROOT + 'x360_work/rexglue_extra_functions.txt') if l.strip() and not l.startswith('#')]
    out += ['', '# From x360_work/rexglue_extra_functions.txt: .pdata functions the analyzer misses (vtable-only thunks etc.)']
    out += ['"%s" = { }' % a for a in extra]
    open(ROOT + 'game/analysis_functions.toml', 'w').write('\n'.join(out) + '\n')

    st = tomllib.load(open(ROOT + 'x360_work/switch_tables.toml', 'rb'))
    out = ['# Generated by tools/to_rexglue.py from x360_work/switch_tables.toml (tools/find_jumptables.py). Do not edit by hand.', '']
    for s in st['switch']:
        out += ['[[switch_tables]]', 'address = 0x%08X' % s['base'], 'register = %d' % s['r'],
                'labels = [%s]' % ', '.join('0x%08X' % l for l in s['labels']), '']
    open(ROOT + 'game/analysis_switch_tables.toml', 'w').write('\n'.join(out))
    print('functions', len(funcs), '+ extra', len(extra), 'switch tables', len(st['switch']))


if __name__ == '__main__':
    main()
