#!/usr/bin/env python3
"""S0: extract leaf functions with loops from the XenonRecomp output into one C++ file for the micro-benchmark.

  S0_PPC=<recomp dir> select.py OUTDIR [LIST.txt [CHUNKS [TAG]]]     # LIST: 'ADDR ICOUNT' per line (from the PC sweep); without a list: all leaf loop functions (candidates for the PC sweep)

Leaf = no calls to other functions, no indirect calls, no traps. Loop = a goto to a label placed earlier in the body.
Each guest instruction gets an S0_I() marker (counts executed instructions in the counting build, empty otherwise).
"""
import glob, os, re, sys

PPC = os.environ.get('S0_PPC', '/home/lucidfear/Projects/mgr-nx/x360_work/ppc').rstrip('/') + '/'
fre = re.compile(r'PPC_FUNC_IMPL\(__imp__sub_([0-9A-F]+)\) \{\n(.*?)\n\}\n', re.S)
call = re.compile(r'\b\w+\(ctx, base\)')


def candidates():
    for f in sorted(glob.glob(PPC + 'ppc_recomp.*.cpp')):
        t = open(f).read()
        for m in fre.finditer(t):
            body = m.group(2)
            if call.search(body) or 'PPC_CALL_INDIRECT' in body or 'debugtrap' in body or 'longjmp' in body: continue
            pos = {l: body.index('loc_%s:' % l) for l in set(re.findall(r'^loc_([0-9A-F]+):', body, re.M))}
            if any(g.group(1) in pos and pos[g.group(1)] < g.start() for g in re.finditer(r'goto loc_([0-9A-F]+);', body)):
                yield m.group(1), body


def main():
    outdir = sys.argv[1]
    keep = dict(l.split()[:2] for l in open(sys.argv[2]) if l.strip()) if len(sys.argv) > 2 else None    # ADDR ICOUNT per line
    chunks = int(sys.argv[3]) if len(sys.argv) > 3 else 16
    tag = sys.argv[4] if len(sys.argv) > 4 else 'base'                     # variant name: functions f_<tag>_ADDR, table s0_table_<tag>
    os.makedirs(outdir, exist_ok=True)
    names = []; outs = [open(os.path.join(outdir, 'chunk_%02d.cpp' % i), 'w') for i in range(chunks)]
    for o in outs: o.write('// generated by tools/s0bench/select.py from the local XenonRecomp output -- do not commit\n#include "s0_common.h"\n\n')
    for a, body in candidates():
        if keep is not None and a not in keep: continue
        body = re.sub(r'^\t// ', '\tS0_I(); // ', body, flags=re.M)
        outs[len(names) % chunks].write('extern "C" PPC_FUNC(f_%s_%s) {\n%s\n}\n\n' % (tag, a, body))
        names.append((a, int(keep[a]) if keep else 0, int('_mm_' in body)))
    for o in outs: o.close()
    with open(os.path.join(outdir, 'table.cpp'), 'w') as o:
        o.write('#include "s0_common.h"\n')
        o.write(''.join('extern "C" PPC_FUNC(f_%s_%s);\n' % (tag, a) for a, n, v in names))
        o.write('static const S0Cand cands[] = {\n%s};\n' % ''.join('\t{0x%s, f_%s_%s, %dull, %d},\n' % (a, tag, a, n, v) for a, n, v in names))
        o.write('extern const S0Table s0_table_%s = {"%s", cands, %d};\nstatic S0Register reg(&s0_table_%s);\n' % (tag, tag, len(names), tag))
    print(outdir, len(names), 'functions in', chunks, 'chunks')


if __name__ == '__main__':
    main()
